"""把 display_driver + ui.py + 啟動邏輯合成單一檔案，供模擬器的 ?script= 載入。

用法：
    python app/make_sim.py
產出：
    app/_sim_all.py
"""

import os

HERE = os.path.dirname(os.path.abspath(__file__))

HEADER = "# AUTO-GENERATED by make_sim.py - 請勿手動編輯\n"

BOOT = '''

# ---------------- 啟動（模擬器） ----------------
def _boot():
    try:
        start()
    except Exception as e:
        # 模擬器看不到 print/stderr，出錯時直接把訊息畫在畫面上
        try:
            scr = lv.obj()
            scr.set_style_bg_color(col(BG), 0)
            lb = lv.label(scr)
            lb.set_text("ERROR\\n" + repr(e))
            lb.set_style_text_color(col(0xFF6B6B), 0)
            lb.set_style_text_font(lv.font_montserrat_12, 0)
            lb.set_long_mode(lv.label.LONG.WRAP)
            lb.set_width(220)
            lb.center()
            lv.screen_load(scr)
            lv.timer_handler()
        except Exception:
            pass
    display_driver.run_event_loop()


_boot()
'''


def main():
    with open(os.path.join(HERE, "ui.py"), "r", encoding="utf-8") as f:
        ui_src = f.read()

    out = HEADER + "import display_driver\n\n" + ui_src + BOOT

    path = os.path.join(HERE, "_sim_all.py")
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(out)
    print("wrote %s (%d bytes)" % (path, len(out.encode("utf-8"))))


if __name__ == "__main__":
    main()
